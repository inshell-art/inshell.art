import { createHash } from "node:crypto";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ARTIFACT_ID = "thought-v2-stable-look-meaningful-boundaries-20260714T035935Z";
const MANIFEST_SHA256 = "ac838251d86bea1a5e3c4340cb1a1f0aba9e2a663245e4489ef0fd2788ea48dd";
const MANIFEST_PATH = `artifacts/thought-v2/releases/${ARTIFACT_ID}/manifest.json`;
const RELEASE_BASE_PATH = `artifacts/thought-v2/releases/${ARTIFACT_ID}`;
const PUBLIC_BASE_PATH = `/artifacts/thought-v2/${ARTIFACT_ID}`;

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const publicReleaseDir = resolve(
  repoRoot,
  "apps/home/public/artifacts/thought-v2",
  ARTIFACT_ID,
);
const generatedModule = resolve(
  repoRoot,
  "packages/shared/src/thoughtV2Artifact.generated.ts",
);

const arg = (name) => {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
};

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));

const assert = (condition, message) => {
  if (!condition) throw new Error(message);
};

const checksumMap = (file) => {
  const entries = readFileSync(file, "utf8")
    .split(/\r?\n/u)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const match = line.match(/^([a-f0-9]{64})\s+\*?(.+)$/iu);
      assert(match, `Invalid SHA256SUMS line: ${line}`);
      return [match[2], match[1].toLowerCase()];
    });
  return new Map(entries);
};

const verifyRelease = (releaseDir, manifest) => {
  const sums = checksumMap(join(releaseDir, "SHA256SUMS.txt"));
  for (const entry of manifest.files) {
    const file = join(releaseDir, entry.path);
    assert(existsSync(file), `Manifest file missing: ${entry.path}`);
    const actual = sha256(readFileSync(file));
    assert(actual === entry.sha256, `Manifest checksum mismatch: ${entry.path}`);
    assert(sums.get(entry.path) === actual, `SHA256SUMS mismatch: ${entry.path}`);
  }
};

const generatedSource = (manifest, sampleIndex) => {
  const files = Object.fromEntries(manifest.files.map((entry) => [entry.path, entry.sha256]));
  const samples = sampleIndex.samples
    .filter((sample) => sample.fixtureId !== null)
    .map((sample) => ({
      file: sample.file,
      fixtureId: sample.fixtureId,
      fixtureName: sample.fixtureName,
      corpusId: sample.corpusId,
      corpusName: sample.corpusName,
      promptLine: sample.promptLine,
      agentLine: sample.agentLine,
      promptByteLength: sample.prompt.byteLength,
      agentByteLength: sample.agent.byteLength,
      animated: sample.animated,
    }));

  const expectedWorkSamples = manifest.files.filter((entry) =>
    entry.path.startsWith("samples/works/") && entry.path.endsWith(".svg"),
  ).length;
  assert(
    samples.length === expectedWorkSamples,
    `Expected ${expectedWorkSamples} work samples, found ${samples.length}`,
  );

  return `// Generated by scripts/sync-thought-v2-artifact.mjs. Do not edit manually.\n\n` +
    `export const THOUGHT_V2_ARTIFACT = ${JSON.stringify({
      artifactId: ARTIFACT_ID,
      channel: manifest.channel,
      manifestPath: MANIFEST_PATH,
      manifestSha256: MANIFEST_SHA256,
      publicBasePath: PUBLIC_BASE_PATH,
      releaseBasePath: RELEASE_BASE_PATH,
      files,
    }, null, 2)} as const;\n\n` +
    `export type ThoughtV2ArtifactSample = {\n` +
    `  file: string;\n` +
    `  fixtureId: string;\n` +
    `  fixtureName: string;\n` +
    `  corpusId: string;\n` +
    `  corpusName: string;\n` +
    `  promptLine: string;\n` +
    `  agentLine: string;\n` +
    `  promptByteLength: number;\n` +
    `  agentByteLength: number;\n` +
    `  animated: boolean;\n` +
    `};\n\n` +
    `export const THOUGHT_V2_ARTIFACT_SAMPLES: readonly ThoughtV2ArtifactSample[] = ${JSON.stringify(samples, null, 2)};\n\n` +
    `export const thoughtV2ArtifactSampleUrl = (sample: ThoughtV2ArtifactSample): string =>\n` +
    `  \`${PUBLIC_BASE_PATH}/\${sample.file}\`;\n`;
};

const verifyPinnedOutput = () => {
  const manifestFile = join(publicReleaseDir, "manifest.json");
  assert(existsSync(manifestFile), `Pinned manifest missing: ${manifestFile}`);
  const manifestRaw = readFileSync(manifestFile);
  assert(sha256(manifestRaw) === MANIFEST_SHA256, "Pinned manifest hash mismatch");
  const manifest = JSON.parse(manifestRaw.toString("utf8"));
  assert(manifest.artifact_id === ARTIFACT_ID, "Pinned artifact id mismatch");
  verifyRelease(publicReleaseDir, manifest);

  const sampleIndex = readJson(join(publicReleaseDir, "samples/index.json"));
  const expectedModule = generatedSource(manifest, sampleIndex);
  assert(existsSync(generatedModule), `Generated module missing: ${generatedModule}`);
  assert(readFileSync(generatedModule, "utf8") === expectedModule, "Generated artifact metadata is stale");

  console.log(`[thought-v2-artifact] verified ${ARTIFACT_ID}`);
  console.log(`[thought-v2-artifact] manifest sha256 ${MANIFEST_SHA256}`);
  console.log(
    `[thought-v2-artifact] work samples ${sampleIndex.samples.filter((sample) => sample.fixtureId !== null).length}`,
  );
};

if (process.argv.includes("--check")) {
  verifyPinnedOutput();
  process.exit(0);
}

const sourceRoot = arg("--from");
assert(sourceRoot, "Usage: node scripts/sync-thought-v2-artifact.mjs --from /path/to/THOUGHT");
const source = resolve(repoRoot, sourceRoot);
const latest = readJson(join(source, "artifacts/thought-v2/latest.json"));
assert(latest.artifact_id === ARTIFACT_ID, `latest artifact mismatch: ${latest.artifact_id}`);
assert(latest.manifest_path === MANIFEST_PATH, `latest manifest path mismatch: ${latest.manifest_path}`);
assert(latest.manifest_sha256 === MANIFEST_SHA256, `latest manifest hash mismatch: ${latest.manifest_sha256}`);

const sourceReleaseDir = join(source, RELEASE_BASE_PATH);
const manifestRaw = readFileSync(join(source, MANIFEST_PATH));
assert(sha256(manifestRaw) === MANIFEST_SHA256, "Source manifest hash mismatch");
const manifest = JSON.parse(manifestRaw.toString("utf8"));
verifyRelease(sourceReleaseDir, manifest);

rmSync(publicReleaseDir, { recursive: true, force: true });
mkdirSync(dirname(publicReleaseDir), { recursive: true });
cpSync(sourceReleaseDir, publicReleaseDir, { recursive: true });

const sampleIndex = readJson(join(sourceReleaseDir, "samples/index.json"));
mkdirSync(dirname(generatedModule), { recursive: true });
writeFileSync(generatedModule, generatedSource(manifest, sampleIndex));

verifyPinnedOutput();
