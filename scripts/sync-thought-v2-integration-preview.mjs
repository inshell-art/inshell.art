#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactId = "thought-v2-noncanonical-integration-preview-20260725-r7";
const sourceTag = artifactId;
const sourceCommit = "be0e9a5088856d1ab9262d86f4c2fead4a788867";
const manifestSha256 = "b2eb9fb0e5ed3b7ce11a46726b1f9b9d93d6a7868317b2b219076d6c6b978dbd";
const destination = path.join(
  root,
  "apps",
  "thought",
  "integration-preview",
  "releases",
  artifactId,
);
const lockFile = path.join(root, "apps", "thought", "integration-preview", "consumer-lock.json");
const generatedFile = path.join(
  root,
  "apps",
  "thought",
  "src",
  "thought-v2-integration-preview.generated.ts",
);
const localSpecFile = path.join(root, "apps", "thought", "spec", "THOUGHT.v2.local.md");

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const fromIndex = args.indexOf("--from");
const sourceRepo = path.resolve(root, fromIndex >= 0 ? args[fromIndex + 1] : "../THOUGHT");
const source = path.join(
  sourceRepo,
  "artifacts",
  "thought-v2-integration-preview",
  "releases",
  artifactId,
);

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const readJson = async (file) => JSON.parse(await fs.readFile(file, "utf8"));

async function verifyRelease(directory) {
  const manifestBytes = await fs.readFile(path.join(directory, "manifest.json"));
  const actualManifestSha256 = sha256(manifestBytes);
  if (actualManifestSha256 !== manifestSha256) {
    throw new Error(`integration preview manifest mismatch: ${actualManifestSha256}`);
  }

  const manifest = JSON.parse(manifestBytes.toString("utf8"));
  if (
    manifest.artifactId !== artifactId ||
    manifest.classification !== "noncanonical-integration-preview" ||
    manifest.flags?.productionConsumable !== false ||
    manifest.flags?.deploymentAuthorized !== false ||
    manifest.flags?.registrationAuthorized !== false
  ) {
    throw new Error("integration preview classification or safety flags mismatch");
  }

  for (const entry of manifest.files ?? []) {
    const bytes = await fs.readFile(path.join(directory, entry.path));
    if (bytes.length !== entry.byteLength || sha256(bytes) !== entry.sha256) {
      throw new Error(`integration preview file mismatch: ${entry.path}`);
    }
  }

  return manifest;
}

function lockFromManifest(manifest) {
  return {
    schema: "inshell.thought.integration-preview-consumer-lock.v1",
    artifactId,
    classification: manifest.classification,
    channel: manifest.channel,
    manifestSha256,
    sourceTag,
    sourceCommit,
    productionConsumable: false,
    deploymentAuthorized: false,
    registrationAuthorized: false,
    compatibility: manifest.compatibility,
  };
}

function generatedSource(lock, specText) {
  return `// Generated by scripts/sync-thought-v2-integration-preview.mjs. Do not edit.\n` +
    `export const THOUGHT_V2_INTEGRATION_PREVIEW = ${JSON.stringify(lock, null, 2)} as const;\n` +
    `export const THOUGHT_V2_INTEGRATION_PREVIEW_SPEC_TEXT = ${JSON.stringify(specText)};\n`;
}

async function main() {
  if (!checkOnly) {
    const checkedOutCommit = execFileSync(
      "git",
      ["-C", sourceRepo, "rev-parse", "HEAD"],
      { encoding: "utf8" },
    ).trim();
    if (checkedOutCommit !== sourceCommit) {
      throw new Error(`integration preview source commit mismatch: ${checkedOutCommit}`);
    }
    const manifest = await verifyRelease(source);
    await fs.rm(destination, { force: true, recursive: true });
    await fs.mkdir(path.dirname(destination), { recursive: true });
    await fs.cp(source, destination, { recursive: true });
    const lock = lockFromManifest(manifest);
    const specText = await fs.readFile(
      path.join(source, "protocol", "current", "v2", "THOUGHT.v2.md"),
      "utf8",
    );
    await fs.writeFile(lockFile, `${JSON.stringify(lock, null, 2)}\n`, "utf8");
    await fs.writeFile(generatedFile, generatedSource(lock, specText), "utf8");
    await fs.writeFile(localSpecFile, specText, "utf8");
  }

  const manifest = await verifyRelease(destination);
  const expectedLock = lockFromManifest(manifest);
  const actualLock = await readJson(lockFile);
  if (JSON.stringify(actualLock) !== JSON.stringify(expectedLock)) {
    throw new Error("integration preview consumer lock mismatch");
  }
  const specText = await fs.readFile(
    path.join(destination, "protocol", "current", "v2", "THOUGHT.v2.md"),
    "utf8",
  );
  if ((await fs.readFile(generatedFile, "utf8")) !== generatedSource(expectedLock, specText)) {
    throw new Error("integration preview generated module mismatch");
  }
  if ((await fs.readFile(localSpecFile, "utf8")) !== specText) {
    throw new Error("integration preview local THOUGHT spec mismatch");
  }

  console.log(JSON.stringify({ artifactId, fileCount: manifest.files.length, manifestSha256, verified: true }));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
